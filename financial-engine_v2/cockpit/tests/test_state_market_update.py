def test_get_latest_market_update_report_filtered_by_run_type(
    store: StateStore,
) -> None:
    store.save_market_update_report(
        run_type="noon", report_date="2026-04-20", status="ok", summary={"v": 1}
    )
    time.sleep(0.01)
    store.save_market_update_report(
        run_type="final", report_date="2026-04-20", status="ok", summary={"v": 2}
    )
    time.sleep(0.01)
    store.save_market_update_report(
        run_type="noon", report_date="2026-04-20", status="ok", summary={"v": 3}
    )

    latest_any = store.get_latest_market_update_report()
    assert latest_any is not None
    assert latest_any["summary"] == {"v": 3}

    latest_final = store.get_latest_market_update_report(run_type="final")
    assert latest_final is not None
    assert latest_final["summary"] == {"v": 2}

    latest_noon = store.get_latest_market_update_report(run_type="noon")
    assert latest_noon is not None
    assert latest_noon["summary"] == {"v": 3}


