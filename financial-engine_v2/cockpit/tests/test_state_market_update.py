"""Tests for market_update_reports + market_update_followups persistence.

P2 of the cockpit verbal market updates plus holdings v1.

These tables hold cockpit-local report snapshots and queued follow-up actions
generated by the noon-preview / final-report orchestrator (P5). Per
SYSTEM_CONTRACT §1.2 they are client-side state only, not financial truth.
"""
from __future__ import annotations

import time
from pathlib import Path

import pytest

from cockpit.storage.state import StateStore


@pytest.fixture()
def store(tmp_path: Path) -> StateStore:
    return StateStore(str(tmp_path / "state.db"))


