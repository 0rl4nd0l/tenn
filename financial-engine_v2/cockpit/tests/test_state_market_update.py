def test_save_market_update_report_persists_and_returns_id(store: StateStore) -> None:
    summary = {
        "winners": [{"ticker": "BHP", "pct": 4.2}],
        "losers": [{"ticker": "CBA", "pct": -1.1}],
        "holdings_impact": [],
    }
    report_id = store.save_market_update_report(
        run_type="noon",
        report_date="2026-04-20",
        status="ok",
        summary=summary,
    )
    assert isinstance(report_id, str) and report_id

    fetched = store.get_latest_market_update_report()
    assert fetched is not None
    assert fetched["report_id"] == report_id
    assert fetched["run_type"] == "noon"
    assert fetched["report_date"] == "2026-04-20"
    assert fetched["status"] == "ok"
    assert fetched["summary"] == summary  # round-trips as dict
    assert fetched["created_at"]


def test_save_market_update_report_accepts_all_run_types(store: StateStore) -> None:
    for run_type in ("noon", "final", "manual"):
        store.save_market_update_report(
            run_type=run_type,
            report_date="2026-04-20",
            status="ok",
            summary={"run_type_check": run_type},
        )
    rows = store.list_market_update_reports()
    types = sorted(r["run_type"] for r in rows)
    assert types == ["final", "manual", "noon"]


